-- ============================================================================
-- VSCode 风格快捷键映射
-- 说明：终端 Neovim 不支持 Cmd 键，用 Ctrl/Option 替代
-- Cmd 键（<D-...>）仅在 Neovide 等 GUI 客户端可用
-- ============================================================================

local map = vim.keymap.set

-- ----------------------------------------------------------------------------
-- 文件操作（终端可用 Ctrl 版本）
-- ----------------------------------------------------------------------------
map({ "n", "i", "v" }, "<C-s>", "<Cmd>w<CR>", { desc = "保存文件" })           -- Cmd+S -> Ctrl+S
map({ "n", "i", "v" }, "<C-w>", "<Cmd>q<CR>", { desc = "关闭当前窗口" })       -- Cmd+W -> Ctrl+W

-- ----------------------------------------------------------------------------
-- 编辑操作
-- ----------------------------------------------------------------------------
map({ "n", "v" }, "<C-z>", "u", { desc = "撤销" })                              -- Cmd+Z -> Ctrl+Z
map({ "n", "v" }, "<C-y>", "<C-r>", { desc = "重做" })                          -- Cmd+Y -> Ctrl+Y
map({ "n", "v" }, "<C-x>", '"+d', { desc = "剪切到系统剪贴板" })                -- Cmd+X -> Ctrl+X
map({ "n", "v" }, "<C-c>", '"+y', { desc = "复制到系统剪贴板" })                -- Cmd+C -> Ctrl+C
map({ "n", "v" }, "<C-v>", '"+p', { desc = "从系统剪贴板粘贴" })                -- Cmd+V -> Ctrl+V
map("i", "<C-v>", '<C-r>+', { desc = "从系统剪贴板粘贴（插入模式）" })

-- ----------------------------------------------------------------------------
-- 光标移动
-- ----------------------------------------------------------------------------
map({ "n", "i", "v" }, "<C-a>", "<Esc>ggVG", { desc = "全选" })                 -- Cmd+A -> Ctrl+A

-- ----------------------------------------------------------------------------
-- 搜索替换
-- ----------------------------------------------------------------------------
map({ "n", "v" }, "<C-f>", "/", { desc = "搜索" })                              -- Cmd+F -> Ctrl+F
map("n", "<C-h>", ":%s//g<Left><Left>", { desc = "全局替换" })                  -- Cmd+H -> Ctrl+H

-- ----------------------------------------------------------------------------
-- 注释（使用 LazyVim 默认的 gc 快捷键，这里添加 Option+/ 作为替代）
-- ----------------------------------------------------------------------------
map({ "n", "v" }, "<M-/>", "gcc", { desc = "切换行注释", remap = true })        -- Cmd+/ -> Option+/

-- ----------------------------------------------------------------------------
-- 代码格式化
-- ----------------------------------------------------------------------------
map({ "n", "v" }, "<M-S-f>", function() vim.lsp.buf.format() end, { desc = "格式化代码" })  -- Shift+Option+F

-- ----------------------------------------------------------------------------
-- 窗口分屏
-- ----------------------------------------------------------------------------
map("n", "<C-\\>", "<Cmd>vsplit<CR>", { desc = "垂直分屏" })                    -- Cmd+\ -> Ctrl+\
map("n", "<C-_>", "<Cmd>split<CR>", { desc = "水平分屏" })                       -- Cmd+- -> Ctrl+-

-- ----------------------------------------------------------------------------
-- 行操作
-- ----------------------------------------------------------------------------
map("n", "<M-C-k>", "<Cmd>m .-2<CR>==", { desc = "向上移动行" })                 -- Option+Up -> Option+Ctrl+K
map("n", "<M-C-j>", "<Cmd>m .+1<CR>==", { desc = "向下移动行" })                 -- Option+Down -> Option+Ctrl+J
map("n", "<M-S-C-k>", "yyP", { desc = "向上复制行" })                            -- Shift+Option+Up
map("n", "<M-S-C-j>", "yyp", { desc = "向下复制行" })                            -- Shift+Option+Down

-- ----------------------------------------------------------------------------
-- GUI 专用（Neovide）- 仅在 GUI 客户端生效，用 Cmd 键
-- ----------------------------------------------------------------------------
if vim.g.neovide then
  map({ "n", "i", "v" }, "<D-s>", "<Cmd>w<CR>", { desc = "[GUI] 保存文件" })
  map({ "n", "i", "v" }, "<D-w>", "<Cmd>q<CR>", { desc = "[GUI] 关闭窗口" })
  map({ "n", "i", "v" }, "<D-a>", "<Esc>ggVG", { desc = "[GUI] 全选" })
  map({ "n", "v" }, "<D-x>", '"+d', { desc = "[GUI] 剪切" })
  map({ "n", "v" }, "<D-c>", '"+y', { desc = "[GUI] 复制" })
  map({ "n", "v" }, "<D-v>", '"+p', { desc = "[GUI] 粘贴" })
  map("i", "<D-v>", '<C-r>+', { desc = "[GUI] 粘贴（插入模式）" })
  map({ "n", "v" }, "<D-z>", "u", { desc = "[GUI] 撤销" })
  map({ "n", "v" }, "<D-f>", "/", { desc = "[GUI] 搜索" })
end
